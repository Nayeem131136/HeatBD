export function getFilteredTips(conditionId: number, feelsLike: number) {
  const conditions = getWeatherConditions(conditionId, feelsLike);
  let weatherType = 'mild';
  if (conditions.isRain) weatherType = 'rain';
  else if (conditions.isCold) weatherType = 'cold';
  else if (conditions.isHot) weatherType = 'hot';

  return ALL_TIPS.filter(tip =>
    tip.weather.includes('all') || tip.weather.includes(weatherType)
  );
}

