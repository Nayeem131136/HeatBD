export interface SeverityInfo {
  level: string;
  color: string;
  label: string;
  message: string;
}

export function getSeverity(feelsLike: number): SeverityInfo {
  if (feelsLike < 28) return { level: 'safe', color: '#00E676', label: 'আবহাওয়া স্বাভাবিক 🌿', message: 'আজকের আবহাওয়া আরামদায়ক। পর্যাপ্ত পানি পান করুন।' };
  if (feelsLike < 32) return { level: 'moderate', color: '#FFD600', label: 'মাঝারি গরম ☀️', message: 'বাইরে বের হলে সতর্ক থাকুন। পানি সাথে রাখুন।' };
  if (feelsLike < 36) return { level: 'caution', color: '#FF6D00', label: 'গরম বাড়ছে ⚠️', message: 'শিশু ও বৃদ্ধদের বাইরে নেওয়া থেকে বিরত থাকুন।' };
  if (feelsLike < 40) return { level: 'danger', color: '#FF3D00', label: 'বিপদ সংকেত! 🔥', message: 'দুপুর ১১টা–৪টা ঘরে থাকুন। প্রতি ঘণ্টায় পানি পান করুন।' };
  return { level: 'extreme', color: '#FF1744', label: 'জরুরি সতর্কতা! 🚨', message: 'হিটস্ট্রোকের মারাত্মক ঝুঁকি! এখনই ঘরে আশ্রয় নিন।' };
}

